const fs = require('fs');
const path = require('path');

// ----------------- Configuration -----------------
const INPUT_FILE  = 'index.html';   // your dashboard HTML file
const OUTPUT_FILE = 'dashboard_html.h';  // generated header file
const VAR_NAME    = 'dashboard_html';    // C++ variable name
// -------------------------------------------------

// ---- Try to use html-minifier, fallback to basic whitespace reduction ----
let minify;
try {
  minify = require('html-minifier').minify;
} catch (e) {
  console.warn('⚠  html-minifier not installed. Using basic minification.');
  console.warn('   Run: npm install html-minifier');
  // fallback: simple whitespace & comment removal
  minify = (html) => {
    return html
      .replace(/<!--[\s\S]*?-->/g, '')            // remove comments
      .replace(/\s+/g, ' ')                       // collapse whitespace
      .replace(/>\s+</g, '><')                    // remove spaces between tags
      .trim();
  };
}

// ---- Generate a safe delimiter for raw string literal ----
function createRawLiteral(content, varName) {
  let delimiter = 'HTML_DELIMITER';
  let attempt = 0;
  // Ensure the content does not contain the closing sequence: )delimiter"
  while (content.includes(`)${delimiter}"`)) {
    delimiter = `HTML_DELIMITER_${++attempt}`;
  }
  const literal = `R"${delimiter}(\n${content}\n)${delimiter}"`;
  return `const char ${varName}[] = ${literal};`;
}

// ---- Main process ----
try {
  // Read input HTML
  const html = fs.readFileSync(INPUT_FILE, 'utf8');
  console.log(`Read ${INPUT_FILE} (${html.length} bytes)`);

  // Minify
  const minified = minify(html, {
    collapseWhitespace: true,
    removeComments: true,
    minifyCSS: true,
    minifyJS: true
  });
  console.log(`Minified to ${minified.length} bytes`);

  // Generate raw string literal
  const rawLiteralCode = createRawLiteral(minified, VAR_NAME);

  // Build header content
  const headerContent =
`// Auto-generated by html_to_header.js – DO NOT EDIT
#ifndef DASHBOARD_HTML_H
#define DASHBOARD_HTML_H

${rawLiteralCode}

#endif // DASHBOARD_HTML_H
`;

  // Write header file
  fs.writeFileSync(OUTPUT_FILE, headerContent, 'utf8');
  console.log(`Generated header: ${OUTPUT_FILE}`);
} catch (err) {
  console.error('Error:', err.message);
  process.exit(1);
}
